export function chooseBekovichLine(event,previousId,random=Math.random,{discCount,appraising=false,chest}={}){
 const pool=BEKOVICH_DIALOGUE.filter(l=>l.event===event&&(l.id!==11||discCount===undefined||discCount===3)&&(!appraising||l.id!==10)&&(l.id!==24||discCount===undefined||discCount>0));
 const fresh=pool.filter(l=>l.id!==previousId),choices=fresh.length?fresh:pool;
 if(!choices.length)throw Error('Unknown dialogue event');
 const line=choices[Math.min(choices.length-1,Math.floor(random()*choices.length))];
 if(line.id===17&&chest==='parcel')return {...line,stage:'Передаёт посылку',text:'Держи свою посылку. Надеюсь, удача сегодня на твоей стороне.'};
 if(line.id===17&&chest==='stash')return {...line,stage:'Передаёт контейнер',text:'Держи свой контейнер. Надеюсь, удача сегодня на твоей стороне.'};
 return line;
}
