export function companionGreeting(data){
 if(data.first_visit)return 'Теперь у меня есть память! Наш уголок будет ждать тебя на любом устройстве.';
 const away=data.away_ms||0,habits=data.habits||{};
 if(away>=86400000)return 'Ты вернулся! Я уже соскучился. Проверял антенну и ждал тебя.';
 if(away>=21600000)return 'О, вот и ты! Я берегу нашу полочку. Посидим вместе?';
 if(habits.pets>=10)return 'Мой любимый человек вернулся! Можно потом чуть-чуть погладить корпус?';
 if((habits.songs||0)>=3)return 'Привет! Кассета на месте. Снова устроим маленькие танцы?';
 return habits.visits>1?'Снова вместе. Как прошёл твой день?':'Бип! Рад видеть тебя в нашем уголке.';
}
export function companionIdle(habits={},favorite){
 if(favorite)return `«${favorite}» всё ещё мой любимый диск. Такая красивая обложка…`;
 if((habits.pets||0)>=10)return 'Корпус чистый, антенна на месте… А поглаживания всё равно самые приятные.';
 if((habits.songs||0)>(habits.stars||0)&&habits.songs>=3)return 'Кажется, мы с тобой любим танцевать. Я даже запомнил движения!';
 if(habits.stars>=3)return 'Интересно, как назвать наше созвездие? Мне нравится смотреть на него с тобой.';
 if(habits.gardens>=3)return 'Наш сад подрастает. Я люблю возвращаться туда с тобой.';
 if(habits.games>=3)return 'Я потренировал свои шаги. В следующий раз покажу!';
 return 'Бип… Антенна на месте. Всё хорошо.';
}
